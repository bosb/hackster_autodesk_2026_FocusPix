ROWS, COLS = 8, 13


def glyph(char):
    """Return the 8-row bitmap (list of strings) for a character."""
    ch = char.upper()
    if ch in _GLYPHS:
        return _GLYPHS[ch]
    return _GLYPHS[" "]


def blank_frame():
    return ["0"] * (ROWS * COLS)


def frame_to_string(grid):
    """grid: 8x13 (list of 8 lists of 13 bits) -> 104-char string."""
    return "".join(str(int(v)) for row in grid for v in row)


def place_glyph(grid, rows, cols, glyph_rows, glyph_cols, on=True):
    """Stamp a glyph (list of 8 bit-strings) onto an 8x13 0/1 grid."""
    for r, row in enumerate(glyph_rows):
        if 0 <= rows + r < ROWS:
            for c, ch in enumerate(row):
                if 0 <= cols + c < COLS and ch == "#":
                    grid[rows + r][cols + c] = 1 if on else 0


def two_digit_frame(text):
    """Two 5-wide digits, centred, with a free gap column for a progress bar."""
    grid = [[0] * COLS for _ in range(ROWS)]
    text = text.zfill(2)[-2:]
    place_glyph(grid, 0, 1, glyph(text[0]), 0)
    place_glyph(grid, 0, 7, glyph(text[1]), 0)
    return grid


def set_progress_bar(grid, fraction, col=6):
    """Vertical progress bar in the gap column (fills from the bottom)."""
    filled = max(0, min(8, int(round(fraction * 8))))
    for r in range(8):
        grid[r][col] = 1 if (7 - r) < filled else 0


def weather_frame(text, icon):
    """Weather: icon (cols 0-4) + two compact digits (cols 6-8 and 10-12)."""
    grid = [[0] * COLS for _ in range(ROWS)]
    place_glyph(grid, 0, 0, _ICONS[icon], 0)
    text = str(text)[-2:].zfill(2)
    digits = [_SMALL_DIGITS.get(c, _SMALL_DIGITS["8"]) for c in text]
    for i, digit in enumerate(digits):
        place_glyph(grid, 2, 6 + i * 4, digit, 0)
    return grid


def blank():
    return frame_to_string(blank_frame())


def render(text):
    """Centre an arbitrary string (5-wide glyphs, 1-col spacing)."""
    grid = [[0] * COLS for _ in range(ROWS)]
    width = len(text) * 6 - 1
    start = max(0, (COLS - width) // 2)
    for i, ch in enumerate(text):
        place_glyph(grid, 0, start + i * 6, glyph(ch), 0)
    return frame_to_string(grid)
